import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  checkedAhead,
  isNotice,
  madeOnDemand,
  noteNotice,
  quotaSpent,
} from './service.js';

describe('quotaSpent', () => {
  const subdl =
    'https://submaker.example.com/addon/cfg/subtitle/subdl_1_2/ara.srt';
  const other =
    'https://submaker.example.com/addon/cfg/subtitle/subsource_9/ara.srt';
  const t0 = Date.UTC(2030, 0, 1);

  it('takes SubDL as spent for an hour after a quota notice, and only SubDL', () => {
    noteNotice(subdl, 'SubDL download quota reached (429)', t0);
    assert.equal(quotaSpent(subdl, t0 + 59 * 60_000), true);
    assert.equal(quotaSpent(other, t0 + 60_000), false);
    assert.equal(quotaSpent(subdl, t0 + 61 * 60_000), false);
  });

  it('ignores notices that are not about quota', () => {
    noteNotice(subdl, 'Translating, please wait…', t0 + 10 * 3600_000);
    assert.equal(quotaSpent(subdl, t0 + 10 * 3600_000 + 1000), false);
  });

  it("ignores another provider's quota notice", () => {
    noteNotice(other, 'OpenSubtitles daily quota reached', t0 + 20 * 3600_000);
    assert.equal(quotaSpent(subdl, t0 + 20 * 3600_000 + 1000), false);
  });
});

describe('checkedAhead', () => {
  it('leaves SubDL subtitles to be checked when opened, as each download spends quota', () => {
    for (const path of [
      '/addon/cfg/subtitle/subdl_3709576_8630594/ara.srt',
      '/addon/cfg/subtitle-content/subdl_3618552_8536004/eng.vtt',
    ])
      assert.equal(
        checkedAhead(`https://submaker.example.com${path}`),
        false,
        path
      );
  });

  it('checks other providers ahead, but never subtitles made on demand', () => {
    const at = (path: string) => `https://submaker.example.com${path}`;
    assert.equal(
      checkedAhead(at('/addon/cfg/subtitle/subsource_10224481/ara.srt')),
      true
    );
    assert.equal(
      checkedAhead(at('/addon/cfg/subtitle/v3_e1_AYZWRb/ara.srt')),
      true
    );
    assert.equal(checkedAhead(at('/addon/cfg/translate/subdl_1_2/ara')), false);
    assert.equal(checkedAhead(at('/addon/cfg/translate/123/ara')), false);
  });

  it('does not mistake a path merely containing "subdl" for SubDL', () => {
    assert.equal(
      checkedAhead('https://subs.example.com/subtitles/mysubdlfan/123.srt'),
      true
    );
  });
});

describe('isNotice', () => {
  it("flags SubMaker's SubDL quota notice, which stands in for a subtitle", () => {
    // The notice as SubMaker served it for Project Hail Mary.
    const notice = [
      '1',
      '00:00:00,000 --> 00:00:03,000',
      'SubDL download quota reached (429)',
      '',
      '2',
      '00:00:03,001 --> 04:00:00,000',
      'This SubDL API key cannot download more files right now.',
      '',
      '3',
      '04:00:01,000 --> 04:00:02,500',
      'This informational subtitle was generated by the addon.',
      '',
    ].join('\n');
    assert.equal(isNotice(notice), true);
  });

  it('leaves a real subtitle alone', () => {
    const at = (n: number) =>
      `00:${String(Math.floor(n / 60)).padStart(2, '0')}:${String(n % 60).padStart(2, '0')},000`;
    const lines: string[] = [];
    for (let i = 0; i < 40; i++) {
      const s = 60 + i * 5;
      lines.push(
        String(i + 1),
        `${at(s)} --> ${at(s + 2)}`,
        `Line ${i + 1}`,
        ''
      );
    }
    assert.equal(isNotice(lines.join('\n')), false);
  });

  it('does not call unreadable text a notice', () => {
    assert.equal(isNotice('not a subtitle at all'), false);
  });
});

describe('madeOnDemand', () => {
  it('flags subtitles made when asked for, which a check would start', () => {
    for (const path of [
      '/addon/cfg/translate/123/ara',
      '/addon/cfg/auto/hash/ara/456',
      '/addon/cfg/learn/123/ara',
      '/addon/cfg/xsync/hash/ara/456',
      '/addon/cfg/xembedded/hash/ara/2',
      '/addon/cfg/file-translate/tt1:1:1',
      '/addon/cfg/sync-subtitles/tt1:1:1',
    ])
      assert.equal(
        madeOnDemand(`https://submaker.example.com${path}`),
        true,
        path
      );
  });

  it('leaves ordinary subtitle files to be checked', () => {
    for (const path of [
      '/addon/cfg/subtitle/abc/ara.srt',
      '/addon/cfg/subtitle-content/abc/eng.vtt',
      '/subtitles/opensubtitles/123.srt',
    ])
      assert.equal(
        madeOnDemand(`https://subs.example.com${path}`),
        false,
        path
      );
  });
});
